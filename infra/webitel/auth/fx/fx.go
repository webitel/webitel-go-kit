// Package authfx wires infra/webitel/auth into an fx application: auth.Dial opens the
// gRPC connection to go.webitel.app through service discovery, and the client
// closes it on stop. It provides *auth.Client and, given a WebitelAPI, *auth.Authorizer.
//
//	fx.New(
//		discoveryfx.Module(discoveryfx.Config{ /* ... */ }),
//		authfx.Module(authfx.Config{}, auditpb.WebitelAPI),
//		fx.Provide(newServer), // takes *auth.Authorizer, passes .Authorize to the interceptors
//	)
//
// The graph must contain a discovery.DiscoveryProvider, for example from
// discoveryfx.Module.
package authfx

import (
	"context"
	"crypto/tls"
	"time"

	"go.opentelemetry.io/contrib/instrumentation/google.golang.org/grpc/otelgrpc"
	"go.uber.org/fx"
	"google.golang.org/grpc"

	"github.com/webitel/webitel-go-kit/infra/discovery"
	"github.com/webitel/webitel-go-kit/infra/webitel/auth"
)

// Config for Module. Zero fields take the defaults of infra/webitel/auth.
type Config struct {
	// Service is the discovery name of the auth service; defaults to auth.DefaultService.
	Service string
	// TLS secures the connection. Nil connects without TLS
	TLS *tls.Config
	// CacheTTL is how long a session is reused; zero takes the default.
	CacheTTL time.Duration
	// DisableCache turns the session cache off.
	DisableCache bool
	// CacheSize bounds the number of cached sessions.
	CacheSize int
	// CallTimeout bounds one UserInfo call.
	CallTimeout time.Duration
}

func (c Config) options() []auth.DialOption {
	var opts []auth.DialOption
	switch {
	case c.DisableCache:
		opts = append(opts, auth.WithCacheTTL(0))
	case c.CacheTTL > 0:
		opts = append(opts, auth.WithCacheTTL(c.CacheTTL))
	}

	// Non-positive values keep the defaults in infra/webitel/auth.
	return append(opts, auth.WithCacheSize(c.CacheSize), auth.WithCallTimeout(c.CallTimeout))
}

type params struct {
	fx.In

	Lifecycle fx.Lifecycle
	Discovery discovery.DiscoveryProvider
}

// Module provides *auth.Client, and *auth.Authorizer when webitelAPI is not nil.
// webitelAPI is the WebitelAPI variable generated by protoc-gen-go-webitel in the
// service package; a service without it passes nil and uses Client.Authenticate.
func Module(cfg Config, webitelAPI any) fx.Option {
	opts := []fx.Option{
		fx.Provide(func(p params) (*auth.Client, error) { return provide(cfg, p) }),
		fx.Invoke(func(*auth.Client) {}),
	}
	if webitelAPI != nil {
		opts = append(opts,
			fx.Provide(func(c *auth.Client) (*auth.Authorizer, error) { return auth.NewAuthorizer(c, webitelAPI) }),
			fx.Invoke(func(*auth.Authorizer) {}),
		)
	}

	return fx.Module("auth", opts...)
}

func provide(cfg Config, p params) (*auth.Client, error) {
	opts := append(cfg.options(),
		auth.WithService(cfg.Service),
		auth.WithTLS(cfg.TLS),
		auth.WithDialOptions(grpc.WithStatsHandler(otelgrpc.NewClientHandler())),
	)

	client, err := auth.Dial(context.Background(), p.Discovery, opts...)
	if err != nil {
		return nil, err
	}

	// Close also closes the connection.
	p.Lifecycle.Append(fx.Hook{
		OnStop: func(context.Context) error { return client.Close() },
	})

	return client, nil
}
